<h2>Privacy Policy - RelocateWhere</h2>

<p><strong>Last updated:</strong> <?php echo esc_html( date( 'F j, Y' ) ); ?></p>

<h3>What Data We Collect</h3>
<p>When you use our cost-of-living tool, we may collect the following information:</p>
<ul>
    <li><strong>Search preferences:</strong> County selection, household type, and income range. This data is used only to generate relevant results and is not stored permanently unless you subscribe.</li>
    <li><strong>Email address (optional):</strong> Only collected if you voluntarily subscribe to contribute local data.</li>
    <li><strong>Contributor data:</strong> If you choose to contribute cost-of-living information, we collect the town-level cost data you submit along with the county and town name.</li>
</ul>

<h3>How We Use Your Data</h3>
<ul>
    <li>To generate and display cost-of-living estimates for your selected county.</li>
    <li>To send you a private contribution form link (if you subscribed).</li>
    <li>To improve the accuracy of our cost-of-living data through human-verified contributions.</li>
    <li>We do <strong>not</strong> sell, rent, or share your personal data with third parties.</li>
</ul>

<h3>Data Security</h3>
<ul>
    <li>Email addresses are stored securely in our database.</li>
    <li>Contributor identity is never disclosed publicly. Only the aggregate data (percentages) are shown.</li>
    <li>Private contribution links use unique tokens and cannot be guessed.</li>
    <li>All data transmission occurs over HTTPS.</li>
</ul>

<h3>Contributor Privacy</h3>
<p>When you contribute cost-of-living data:</p>
<ul>
    <li>Your email address is <strong>never</strong> displayed alongside your contribution.</li>
    <li>Contributions are reviewed manually before being accepted.</li>
    <li>Accepted contributions appear only as aggregate percentages (e.g., "40% Human sources").</li>
    <li>You can request deletion of your data at any time by contacting us.</li>
</ul>

